/* ★S4 하위 스텝 (누적형이라 단조 카운터로 둔다 — S3b 처럼 교체가 아님)
 *   1 = S4a  프레임 수신·검증만
 *   2 = +S4b VER/STAT 조회 + ACK 회신
 *   3 = +S4c CH/PHY/MODE/SCAN 상태 변경
 *  회귀 시 이 값을 낮추면 해당 스텝 이전으로 즉시 복귀한다. */
#define FS_S4   3

#endif /* STEP_CONFIG_H */
