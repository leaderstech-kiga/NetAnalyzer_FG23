/***************************************************************************//**
 * @file    app_log.h
 * @brief   UART 출력 경로 (S1~ 공용) — 진단 로그 + 560B 프레임
 *
 *  ★이 파일이 **UART 출력의 유일한 관문**이다. 다른 곳에서 sl_iostream_write 나
 *   EUSART 를 직접 건드리면 링버퍼 배출과 뒤섞여 프레임이 깨진다.
 *
 *  ★왜 헬퍼를 두나 (2026-07-30, S2 실측에서 발견된 버그의 구조적 방지):
 *   snprintf 는 **잘라 쓰지만 반환값은 "잘리지 않았다면 필요했을 길이"** 다.
 *   그 반환값을 그대로 write 길이로 넘기면 **버퍼 밖을 읽어 전송**한다.
 *   S2 에서 실제로 발생 — 버퍼 96B 인데 UTF-8 한글 때문에 필요 길이 107B →
 *   11B 를 버퍼 밖에서 읽어 보냈고, 터미널에 쓰레기가 찍히고 뒤 문장이 잘렸다.
 *   → 호출부마다 clamp 를 반복하면 언젠가 또 빠뜨린다. **한 곳에서 막는다.**
 *
 *  ★출력은 ASCII 전용:
 *   `FG23_UART_인터페이스.md §1` 은 프레임을 "전부 printable ASCII" 로 규정한다.
 *   진단 로그도 같은 규율로 둔다 — 터미널 인코딩 설정에 무관하게 읽히고,
 *   멀티바이트로 길이 계산이 어긋나는 사고(위 버그)도 원천 차단된다.
 *   → **로그 문자열에 한글을 쓰지 않는다.** (주석은 한글 OK, 출력만 ASCII)
 *   ※ 예외: `_Static_assert` 메시지는 컴파일러 출력이라 UART 로 안 나간다 →
 *     한글 그대로 둔다(빌드 실패 시 읽기 쉬운 편이 낫다).
 *
 * ============================================================================
 *  ★S3b — 논블로킹 TX (step_config.h `FS_TX_NONBLOCKING`)
 * ============================================================================
 *  문제: sl_iostream_write 는 블로킹이다. 560B @115200 ≈ **48.6ms**.
 *   S6 이후 RF 수신과 겹치면 짧은PA 데이터 프레임(프리앰블 80bit ≈ 27ms)을
 *   통째로 놓친다. 스니퍼가 로그 쓰느라 관측을 놓치는 건 본말전도.
 *
 *  해법: 링버퍼에 **복사**하고 즉시 반환, 슈퍼루프에서 폴링으로 배출.
 *
 *  ★[원본 -- 1차 시도: EUSART0_TX_IRQHandler 를 직접 정의 → 링크 실패]
 *   "TX IRQ 는 Power Manager 조건부라 비어 있다"(sl_iostream_uart.c:240~253)를
 *   근거로 삼았으나 **절반만 맞았다**. NVIC 활성화만 조건부이고, 핸들러 심볼은
 *   `autogen/sl_iostream_init_eusart_instances.c:192` 가 무조건 정의한다.
 *   → multiple definition. SDK 소스·템플릿만 보고 **프로젝트 autogen 생성물을
 *     확인하지 않은 것**이 원인. (교훈: 생성물까지 봐야 "확인"이다)
 *
 *  현재 방식(폴링)의 근거:
 *   - IRQ 심볼을 안 건드리므로 iostream 과 충돌 없음.
 *   - 배출 속도: 115200 = 1바이트 87us. 슈퍼루프는 그보다 훨씬 빨리 돌아
 *     회선 속도를 따라간다. 루프가 밀려도 데이터는 링에 남아 **유실 안 됨**(지연만).
 *   - `EUSART_STATUS_TXFL` = "transmit FIFO is not full" (em_eusart.c:446 사용례).
 *
 *  채택 안 한 대안 — SDK async TX(`SL_IOSTREAM_EUSART_VCOM_ASYNC_TX`):
 *   `uart_write()` 가 async 모드에서 `SL_STATUS_NOT_AVAILABLE` 을 반환해
 *   기존 출력이 전부 죽고(`sl_iostream_uart.c`), 비동기 API 는 `sli_` **내부
 *   API** 이며 op·버퍼를 완료 콜백까지 살려야 해 560B 더블버퍼가 필요하다.
 *   → 원칙 1(근거 있는 공개 API) 과 롤백 용이성에서 링버퍼가 낫다.
 ******************************************************************************/
#ifndef APP_LOG_H
#define APP_LOG_H

#include <stddef.h>
#include <stdint.h>

/* 진단 로그 한 줄 최대 길이 (포맷 버퍼). 560B 프레임은 app_log_raw 경로. */
#define APP_LOG_BUF_LEN   192u

/***************************************************************************//**
 * 출력 경로 초기화. **첫 출력 전에 1회** 호출 (rail_app_init 선두).
 *  FS_TX_NONBLOCKING=0 이면 아무 것도 하지 않는다(블로킹 경로).
 ******************************************************************************/
void app_log_init(void);

/***************************************************************************//**
 * 링버퍼 배출 — **슈퍼루프에서 매 회 호출**한다 (app_process_action 선두).
 *  TX FIFO 에 여유가 있는 만큼만 밀어 넣고 즉시 돌아온다(블로킹 아님).
 *  FS_TX_NONBLOCKING=0 이면 아무 것도 하지 않는다.
 ******************************************************************************/
void app_log_tx_poll(void);

/***************************************************************************//**
 * 진단 로그 한 줄 출력 (ASCII 전용, 길이 안전).
 * @param[in] fmt  printf 포맷. **ASCII 문자만** 사용할 것.
 ******************************************************************************/
void app_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

/***************************************************************************//**
 * 원본 바이트열 그대로 송신 (포맷 없음). 560B 프레임 경로.
 *
 *  ★전부-아니면-전무(all-or-nothing): 링 여유가 부족하면 **한 바이트도 안 넣고**
 *   드롭 카운터만 올린다. 560B 프레임을 부분 기록하면 수신측에서 프레임이
 *   깨지므로, 잘려 나가느니 통째로 버리는 편이 낫다.
 ******************************************************************************/
void app_log_raw(const char *data, size_t len);

/***************************************************************************//**
 * 링 여유 부족으로 **버린 바이트 누계**.
 *
 *  ★로그가 밀려도 블로킹하지 않는다 — RF 수신을 막는 것보다 로그를 버리는 게
 *   낫다(스니퍼의 본분은 관측). 대신 조용한 손실이 없도록 세어서 노출한다.
 ******************************************************************************/
uint32_t app_log_dropped(void);

/** 링에 아직 배출 대기 중인 바이트 수 (진단용) */
size_t app_log_pending(void);

#endif /* APP_LOG_H */
