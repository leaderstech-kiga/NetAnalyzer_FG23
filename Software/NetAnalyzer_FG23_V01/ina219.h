/***************************************************************************//**
 * @file    ina219.h
 * @brief   S11a — INA219 전류·전압 감시 (하드웨어 I2C0, slave 0x40)
 *
 *  ★범위: **사람이 읽는 로그까지만.** TYPE='B' 프레임 송신은 S11b 다.
 *   (작업지시_ClaudeCode_S11a_INA219_20261016.md §7 "한 번에 한 변수")
 *
 *  ★회로 (Network_Analyzer_2V0 Sheet 1·4 / 작업지시 §2):
 *     Bat+ ──[R33 0.01Ω]── V_SYS ──→ 벅 VIN
 *             │              │
 *           VIN−(2)       VIN+(1)
 *             └── INA219AID ─┘   SCL(5)=PC02  SDA(6)=PC03  VS(4)=+3.3V
 *                                A0/A1 풀다운 → slave **0x40**
 *     외부 풀업 R57/R58 = 10kΩ  → ★내부 풀업 켜지 마라 (open-drain 구동)
 *
 *  ★극성: VIN+ = V_SYS 측 / VIN− = Bat+ 측 → **`+` = 충전 / `−` = 방전.**
 *   2026-10-14 실측으로 확인됨(Vshunt +5.9mV = 충전 590mA).
 *   → **펌웨어에서 부호를 뒤집지 마라.** (작업지시 §2·§7)
 *
 *  ★이 스텝의 진짜 목적 (작업지시 §1·§5-10):
 *   `FG23_UART_프로토콜_v2_확장안 §0.2` 의 저전압 차단 대기시간이 "값"이 아니라
 *   "창(window)"으로 규정돼 있는데, 그 **상한**을 재려면 전류계가 필요하다.
 *     상한 = BAT_CRITICAL 전압에서 0.7A 부하로 8.4V(팩 BMS 차단)까지 걸리는 시간
 *   → `BAT_CRITICAL` 임계(현 잠정 9.0V)가 이 측정으로 확정된다.
 *
 *  ⚠ **안전**: I2C 는 수동 읽기이고 RF 송신이 없다 → 소방 경보(절대선)와 무관.
 *    다만 **모든 I2C 대기에 타임아웃이 걸려 있어야** 한다. 메인루프를 무한정
 *    막으면 워치독(2.05초)이 문다. ina219.c 의 `i2c_xfer()` 가 그 유일한 창구다.
 ******************************************************************************/
#ifndef INA219_H
#define INA219_H

#include <stdint.h>
#include <stdbool.h>

/***************************************************************************//**
 * S11a 초기화. **`wdog_start()` 보다 앞**에서 한 번 호출한다.
 *
 *  순서: 핀(open-drain) → ★버스 복구 → 라우팅 → I2C_Init → Config/Cal 기록·검증
 *  실패해도 부팅을 막지 않는다 — 1Hz 주기에서 재시도한다.
 ******************************************************************************/
void ina219_init(void);

/***************************************************************************//**
 * 메인루프에서 **매 반복** 호출한다. 내부에서 1Hz 주기를 판단하므로
 * 대부분의 호출은 tick 비교 한 번으로 즉시 반환한다.
 ******************************************************************************/
void ina219_poll(void);

/***************************************************************************//**
 * 누적 I2C 실패 수 (진단용). 0 이 아니면 로그에 `I2C ERR` 가 찍혀 있다.
 ******************************************************************************/
uint32_t ina219_err_count(void);

/***************************************************************************//**
 * 마지막 측정이 유효한가. (S11b 에서 프레임 송신 여부 판단에 쓸 예정)
 ******************************************************************************/
bool ina219_is_ready(void);

#endif /* INA219_H */
